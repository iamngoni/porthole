/// Pins the bytes every other implementation of the protocol must reproduce exactly: pairing, the session
/// handshake, sealing and framing, from fixed keys and nonces. The values live in Protocol/vectors/ so the
/// Dart client's tests can check against the same file.
///
/// The test fails if the Swift code ever produces different bytes. To regenerate after an intended change
/// (which breaks compatibility with every paired device), run `PORTHOLE_WRITE_VECTORS=1 swift test`.
@Suite
struct ContractVectorsTests {
    static let file = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent().deletingLastPathComponent()
        .appendingPathComponent("Protocol/vectors/crypto.json")

    @Test func the_swift_code_still_produces_the_pinned_bytes() throws {
        let vectors = try Self.make()
        let data = try JSONSerialization.data(withJSONObject: vectors, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
        if ProcessInfo.processInfo.environment["PORTHOLE_WRITE_VECTORS"] == "1" {
            try FileManager.default.createDirectory(at: Self.file.deletingLastPathComponent(), withIntermediateDirectories: true)
            try (data + Data("\n".utf8)).write(to: Self.file)
            return
        }
        let pinned = try #require(try? Data(contentsOf: Self.file), "missing \(Self.file.path); run PORTHOLE_WRITE_VECTORS=1 swift test")
        let pinnedObject = try JSONSerialization.jsonObject(with: pinned) as? NSDictionary
        #expect(pinnedObject == vectors as NSDictionary, "the protocol's bytes changed; every other implementation and paired device would break")
    }

    @Test func the_high_bit_case_really_has_the_top_bit_set() throws {
        let vectors = try Self.make()
        let cases = try #require(vectors["pairing"] as? [[String: Any]])
        #expect(cases.contains { ($0["sasBytes"] as? String).map { UInt8($0.prefix(2), radix: 16)! >= 0x80 } ?? false })
        #expect(cases.contains { ($0["sasBytes"] as? String).map { UInt8($0.prefix(2), radix: 16)! < 0x80 } ?? false })
    }

    // MARK: Building the vectors

    static func make() throws -> [String: Any] {
        let first = try pairingCase(deviceNonceByte: 0x11)
        // The code is the 8 HKDF bytes read as an unsigned 64-bit number, mod 10^6. Find a case whose top
        // byte is ≥ 0x80, where reading them as a signed number would give a different code.
        var highBit: [String: Any]?
        var lowBit: [String: Any]?
        for byte in UInt8(0x12)...0xFF {
            let candidate = try pairingCase(deviceNonceByte: byte)
            let top = UInt8((candidate["sasBytes"] as! String).prefix(2), radix: 16)!
            if top >= 0x80, highBit == nil { highBit = candidate }
            if top < 0x80, lowBit == nil { lowBit = candidate }
            if highBit != nil, lowBit != nil { break }
        }
        return [
            "about": "Porthole protocol test vectors. Byte strings are lowercase hex. Strings are UTF-8. Generated by ContractVectorsTests.swift.",
            "pairing": [first, highBit!, lowBit!],
            "session": try sessionCase(secret: Data(hex: first["secret"] as! String)),
            "rejectedPublicKeys": try rejectedKeys(),
            "framing": [Data(), Data("abc".utf8), Data(repeating: 0xAB, count: 300)].map { ["payload": $0.hex, "framed": Framing.frame($0).hex] },
        ]
    }

    static func pairingCase(deviceNonceByte: UInt8) throws -> [String: Any] {
        let devicePrivate = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data((0..<32).map { UInt8($0) }))
        let hostPrivate = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data((0..<32).map { UInt8(255 - $0) }))
        let deviceNonce = Data(repeating: deviceNonceByte, count: 32)
        let hostNonce = Data(repeating: 0x22, count: 32)
        let pairID = "6F1C2A9E-4B7D-4E3A-9C1F-2D8B5E0A7C64"

        var device = DevicePairing(deviceID: "device-7d2f", deviceName: "Ngoni’s iPad 🪟", privateKey: devicePrivate, nonce: deviceNonce)
        var host = HostPairing(hostID: "host-41ac", hostName: "Ngonidzashe’s MacBook Pro", privateKey: hostPrivate, nonce: hostNonce)
        let request = device.start()
        let challenge = try host.receive(request)
        let (reveal, deviceCode) = try device.receive(challenge)
        let hostCode = try host.receive(reveal)
        let confirm = try device.confirm()
        try host.receive(confirm)
        let (complete, paired) = try host.complete(pairID: pairID, at: Date(timeIntervalSince1970: 0))
        let pairedHost = try device.receive(complete)
        #expect(deviceCode == hostCode && paired.secret == pairedHost.secret)

        let transcript = PairingCrypto.transcript(request, challenge, reveal)
        let shared = try PairingCrypto.agree(devicePrivate, with: challenge.hostKey)
        let sas = shared.hkdfDerivedSymmetricKey(using: SHA256.self, salt: transcript, sharedInfo: Data("porthole-sas-v1".utf8), outputByteCount: 8)
            .withUnsafeBytes { Data($0) }
        let unsigned = sas.reduce(UInt64(0)) { $0 << 8 | UInt64($1) }
        #expect(String(format: "%06llu", unsigned % 1_000_000) == deviceCode)

        return [
            "deviceID": request.deviceID,
            "deviceName": request.deviceName,
            "hostID": challenge.hostID,
            "hostName": challenge.hostName,
            "devicePrivateKey": devicePrivate.rawRepresentation.hex,
            "hostPrivateKey": hostPrivate.rawRepresentation.hex,
            "devicePublicKey": reveal.deviceKey.hex,
            "hostPublicKey": challenge.hostKey.hex,
            "deviceNonce": deviceNonce.hex,
            "hostNonce": hostNonce.hex,
            "commitment": request.commitment.hex,
            "sharedSecret": shared.withUnsafeBytes { Data($0) }.hex,
            "transcript": transcript.hex,
            "sasBytes": sas.hex,
            "sasUnsigned": String(unsigned),
            "code": deviceCode,
            "secret": paired.secret.hex,
            "deviceConfirmation": confirm.mac.hex,
            "pairID": pairID,
            "hostConfirmation": complete.mac.hex,
        ]
    }

    static func sessionCase(secret: Data) throws -> [String: Any] {
        let pairID = "6F1C2A9E-4B7D-4E3A-9C1F-2D8B5E0A7C64"
        let hello = SessionHandshake.hello(pairID: pairID, secret: secret, nonce: Data(repeating: 0x33, count: 32))
        let accept = SessionHandshake.accept(hello, secret: secret, nonce: Data(repeating: 0x44, count: 32))
        #expect(SessionHandshake.isValid(hello, secret: secret) && SessionHandshake.isValid(accept, for: hello, secret: secret))
        var deviceChannel = SessionHandshake.channel(role: .device, secret: secret, hello: hello, accept: accept)
        var hostChannel = SessionHandshake.channel(role: .host, secret: secret, hello: hello, accept: accept)
        let plaintexts = [Data(), Data("hi".utf8), Data(#"{"v":2,"msg":{"offer":{"sdp":"v=0…"}}}"#.utf8)]
        func sealAll(_ channel: inout SecureChannel, into other: inout SecureChannel) throws -> [[String: Any]] {
            try plaintexts.map { plaintext in
                let frame = try channel.seal(plaintext)
                #expect(try other.open(frame) == plaintext)
                return ["plaintext": plaintext.hex, "counter": frame.counter, "box": frame.box.hex]
            }
        }
        return [
            "secret": secret.hex,
            "pairID": pairID,
            "helloNonce": hello.nonce.hex,
            "helloMAC": hello.mac.hex,
            "acceptNonce": accept.nonce.hex,
            "acceptMAC": accept.mac.hex,
            "deviceToHost": try sealAll(&deviceChannel, into: &hostChannel),
            "hostToDevice": try sealAll(&hostChannel, into: &deviceChannel),
        ]
    }

    /// Low-order points a peer could send to force a known shared secret. Every implementation must refuse them.
    static func rejectedKeys() throws -> [String] {
        let keys = [
            String(repeating: "00", count: 32),
            "01" + String(repeating: "00", count: 31),
            "e0eb7a7c3b41b8ae1656e3faf19fc46ada098deb9c32b1fd866205165f49b800",
            "5f9c95bca3508c24b1d0b1559c83ef5b04445cc4581c8e86d8224eddd09f1157",
            "ecffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff7f",
        ]
        let device = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data((0..<32).map { UInt8($0) }))
        for key in keys {
            #expect(throws: PairingError.invalidKey, "accepted low-order key \(key)") {
                try PairingCrypto.agree(device, with: Data(hex: key))
            }
        }
        return keys
    }
}

/// Pins the protobuf bytes of one example of every message, in Protocol/vectors/messages.json. The Dart
/// client checks that it decodes each to the same values (given as protobuf's standard JSON) and encodes
/// them back to the same bytes. Regenerate with `PORTHOLE_WRITE_VECTORS=1 swift test` after adding fields.
@Suite
struct MessageVectorsTests {
    static let file = ContractVectorsTests.file.deletingLastPathComponent().appendingPathComponent("messages.json")

    @Test func the_swift_code_still_produces_the_pinned_message_bytes() throws {
        let vectors = try Self.make()
        let data = try JSONSerialization.data(withJSONObject: vectors, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
        if ProcessInfo.processInfo.environment["PORTHOLE_WRITE_VECTORS"] == "1" {
            try (data + Data("\n".utf8)).write(to: Self.file)
            return
        }
        let pinned = try #require(try? Data(contentsOf: Self.file), "missing \(Self.file.path); run PORTHOLE_WRITE_VECTORS=1 swift test")
        #expect(try JSONSerialization.jsonObject(with: pinned) as? NSDictionary == vectors as NSDictionary,
                "message bytes changed; other implementations would no longer understand them")
    }

    @Test func every_vector_decodes_back_to_its_message() throws {
        for vector in try Self.make()["messages"] as! [[String: Any]] {
            let bytes = Data(hex: vector["hex"] as! String)
            switch vector["kind"] as! String {
            case "wire": #expect(try WireCoding.decode(bytes) == .message(try WireMessage(proto: PBWire(serializedBytes: bytes))))
            case "signal": _ = try MessageCoding.decode(SignalMessage.self, from: bytes)
            case "client": _ = try MessageCoding.decode(ClientMessage.self, from: bytes)
            default: _ = try MessageCoding.decode(HostMessage.self, from: bytes)
            }
        }
    }

    static func make() throws -> [String: Any] {
        let point = NormalizedPoint(x: 0.25, y: 0.75)
        let info = StreamInfo(gen: 7, windowID: 4242, title: "Notes — “Ideas” 📝", appName: "Notes",
