                              framesPerSecond: 120)
        let wire: [(String, WireMessage)] = [
            ("pairRequest", .pairRequest(PairRequest(deviceID: "device-7d2f", deviceName: "Ngoni’s iPad", commitment: Data(repeating: 0xC0, count: 32)))),
            ("pairChallenge", .pairChallenge(PairChallenge(hostID: "host-41ac", hostName: "MacBook Pro", hostKey: Data(repeating: 0x11, count: 32), hostNonce: Data(repeating: 0x22, count: 32)))),
            ("pairReveal", .pairReveal(PairReveal(deviceKey: Data(repeating: 0x33, count: 32), deviceNonce: Data(repeating: 0x44, count: 32)))),
            ("pairConfirm", .pairConfirm(PairConfirm(mac: Data(repeating: 0x55, count: 32)))),
            ("pairComplete", .pairComplete(PairComplete(pairID: "6F1C2A9E-4B7D-4E3A-9C1F-2D8B5E0A7C64", mac: Data(repeating: 0x66, count: 32)))),
            ("sessionHello", .sessionHello(SessionHello(pairID: "6F1C2A9E-4B7D-4E3A-9C1F-2D8B5E0A7C64", nonce: Data(repeating: 0x77, count: 32), mac: Data(repeating: 0x88, count: 32)))),
            ("sessionAccept", .sessionAccept(SessionAccept(nonce: Data(repeating: 0x99, count: 32), mac: Data(repeating: 0xAA, count: 32)))),
            ("sealed", .sealed(SealedFrame(counter: 300, box: Data([0xDE, 0xAD, 0xBE, 0xEF])))),
            ("bye", .bye(reason: "version-mismatch")),
        ]
        let signal: [(String, SignalMessage)] = [
            ("hello", .hello(ClientHello(deviceName: "iPhone", viewport: PixelSize(width: 1206, height: 2622), maxFramesPerSecond: 120))),
            ("helloWithoutRate", .hello(ClientHello(deviceName: "iPad", viewport: PixelSize(width: 2360, height: 1640)))),
            ("welcome", .welcome(HostWelcome(hostName: "MacBook Pro"))),
            ("offer", .offer(sdp: "v=0\r\no=- 1 2 IN IP4 127.0.0.1\r\n")),
            ("answer", .answer(sdp: "v=0\r\n")),
            ("candidate", .candidate(IceCandidate(sdp: "candidate:1 1 udp 2122260223 192.168.1.2 54321 typ host", sdpMLineIndex: 0, sdpMid: "0"))),
            ("candidateWithoutMid", .candidate(IceCandidate(sdp: "candidate:2", sdpMLineIndex: 1, sdpMid: nil))),
        ]
        let client: [(String, ClientMessage)] = [
            ("listWindows", .listWindows),
            ("select", .select(windowID: 4242)),
            ("stopStream", .stopStream),
            ("viewport", .viewport(PixelSize(width: 2622, height: 1206))),
            ("ping", .ping(1_760_000_000_123)),
            ("pointer", .pointer(PointerEvent(gen: 7, point: point))),
            ("button", .button(ButtonEvent(gen: 7, point: point, button: .right, isDown: true))),
            ("scroll", .scroll(ScrollEvent(gen: 7, point: point, dx: 0, dy: -0.125, phase: .changed, momentum: .none))),
            ("scrollMomentum", .scroll(ScrollEvent(gen: 7, point: point, dx: 0.01, dy: 0.02, phase: nil, momentum: .began))),
            ("key", .key(KeyEvent(gen: 7, usage: 0x04, isDown: true, modifiers: [.command, .shift]))),
            ("text", .text(TextEvent(gen: 7, text: "héllo 👋"))),
            ("releaseAll", .releaseAll),
            ("thumbnails", .thumbnails(windowIDs: [1, 2, 300], maxLongSide: 480)),
            ("appIcons", .appIcons(bundleIDs: ["com.apple.Safari", "com.apple.Notes"])),
            ("listApps", .listApps),
            ("launch", .launch(bundleID: "com.apple.Calculator")),
        ]
        let host: [(String, HostMessage)] = [
            ("windows", .windows([WindowInfo(id: 4242, title: "Ideas", appName: "Notes", bundleID: "com.apple.Notes", pid: 812,
                                             size: PointSize(width: 900, height: 600), isOnScreen: true),
