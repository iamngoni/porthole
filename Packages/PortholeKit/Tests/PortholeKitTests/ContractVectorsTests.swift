            ("streamStarted", .streamStarted(info)),
            ("geometry", .geometry(StreamInfo(gen: 8, windowID: 4242, title: "", appName: "Notes", pointSize: PointSize(width: 640, height: 400),
                                              pixelSize: PixelSize(width: 1280, height: 800)))),
            ("streamLive", .streamState(gen: 7, state: .live)),
            ("streamPaused", .streamState(gen: 7, state: .paused(reason: "The window is minimized."))),
            ("streamClosed", .streamState(gen: 7, state: .closed)),
            ("error", .error(code: "mac_locked", message: "Unlock the Mac to keep going.")),
            ("pong", .pong(1_760_000_000_123)),
            ("controlAllowed", .control(ControlStatus(allowed: true))),
            ("controlRefused", .control(ControlStatus(allowed: false, reason: "Accessibility is off."))),
            ("thumbnail", .thumbnail(windowID: 4242, jpeg: Data([0xFF, 0xD8, 0xFF, 0xD9]))),
            ("appIcon", .appIcon(bundleID: "com.apple.Notes", png: Data([0x89, 0x50, 0x4E, 0x47]))),
            ("apps", .apps([AppInfo(bundleID: "com.apple.Notes", name: "Notes", isRunning: true),
                            AppInfo(bundleID: "com.apple.Calculator", name: "Calculator", isRunning: false)])),
        ]
        func entry(_ name: String, _ kind: String, _ message: some SwiftProtobuf.Message) throws -> [String: Any] {
            ["name": name, "kind": kind, "hex": try message.serializedData().hex,
             "json": try JSONSerialization.jsonObject(with: Data(message.jsonString().utf8))]
        }
        var messages: [[String: Any]] = []
        for (name, message) in wire { messages.append(try entry(name, "wire", message.proto)) }
        for (name, message) in signal { messages.append(try entry(name, "signal", message.proto)) }
        for (name, message) in client { messages.append(try entry(name, "client", message.proto)) }
        for (name, message) in host { messages.append(try entry(name, "host", message.proto)) }
        return [
            "about": "One example of every Porthole v3 message (Protocol/porthole.proto). kind: wire = Wire, signal = Signal, client = ClientMessage, host = HostMessage. hex is the binary encoding; json is protobuf's standard JSON form of the same message. Generated by ContractVectorsTests.swift.",
            "messages": messages,
        ]
    }
}

extension Data {
    var hex: String { map { String(format: "%02x", $0) }.joined() }

    init(hex: String) {
        self.init(stride(from: 0, to: hex.count, by: 2).map { offset in
            let start = hex.index(hex.startIndex, offsetBy: offset)
            return UInt8(hex[start..<hex.index(start, offsetBy: 2)], radix: 16)!
        })
    }
}
